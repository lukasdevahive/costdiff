// Local static server for CostDiff (no dependency). Listens on 127.0.0.1 only.
// Usage: node scripts/serve.mjs [port]   ->  http://127.0.0.1:8765/
import http from "node:http";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "web");
const PORT = Number(process.argv[2] || process.env.PORT || 8765);
const TYPES = {
  ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".css": "text/css; charset=utf-8",
  ".csv": "text/csv; charset=utf-8", ".txt": "text/plain; charset=utf-8", ".png": "image/png", ".svg": "image/svg+xml",
  ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", ".ico": "image/x-icon", ".json": "application/json",
};

// same response headers as Cloudflare Pages: the "/*" block of web/_headers (generated by configure.mjs)
function siteHeaders() {
  try {
    const lines = fs.readFileSync(path.join(ROOT, "_headers"), "utf8").split(/\r?\n/);
    const out = {};
    let inAll = false;
    for (const l of lines) {
      if (/^\S/.test(l)) inAll = l.trim() === "/*";
      else if (inAll && l.includes(":")) { const i = l.indexOf(":"); out[l.slice(0, i).trim().toLowerCase()] = l.slice(i + 1).trim(); }
    }
    return out;
  } catch { return {}; }
}
const HIDDEN = new Set(["_headers", "_redirects"]); // read by the host, never served

const server = http.createServer((req, res) => {
  if (req.method !== "GET" && req.method !== "HEAD") { res.writeHead(405).end(); return; }
  let rel;
  try { rel = decodeURIComponent(new URL(req.url, "http://x").pathname); } catch { res.writeHead(400).end(); return; }
  if (rel.endsWith("/")) rel += "index.html";
  const file = path.resolve(ROOT, "." + rel);
  if (!file.startsWith(ROOT + path.sep)) { res.writeHead(403).end(); return; }
  fs.stat(file, (err, st) => {
    if (err || !st.isFile() || HIDDEN.has(path.basename(file))) {
      const page404 = path.join(ROOT, "404.html");
      res.writeHead(404, { "content-type": "text/html; charset=utf-8", ...siteHeaders() });
      if (fs.existsSync(page404)) fs.createReadStream(page404).pipe(res); else res.end("404");
      return;
    }
    res.writeHead(200, {
      "x-content-type-options": "nosniff", "referrer-policy": "no-referrer", "x-frame-options": "DENY",
      ...siteHeaders(),
      "content-type": TYPES[path.extname(file).toLowerCase()] || "application/octet-stream",
      "cache-control": "no-cache",
    });
    if (req.method === "HEAD") { res.end(); return; }
    fs.createReadStream(file).pipe(res);
  });
});
server.listen(PORT, "127.0.0.1", () => console.log(`CostDiff: http://127.0.0.1:${PORT}/`));
