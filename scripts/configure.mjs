// Set the statistics code and the Pro survey link, and keep every page's Content-Security-Policy in step.
// Usage: node scripts/configure.mjs [--goatcounter CODE|none] [--form https://tally.so/r/ID|none] [--contact EMAIL|none] [--controller "Name"|none] [--site https://host/path/] [--check]
// --site changes the public address (canonical URLs, sitemap, robots, counted hosts): only with the founder's approval.
// --check only verifies that config.js and the CSP of every page agree (used by the tests).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderPrivacy } from "./privacy_blocks.mjs";

// COSTDIFF_WEB lets the tests work on a copy of the site instead of the real web/ folder
const WEB = process.env.COSTDIFF_WEB ? path.resolve(process.env.COSTDIFF_WEB) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "web");
const CONFIG = path.join(WEB, "js", "config.js");

export function readConfig(text = fs.readFileSync(CONFIG, "utf8")) {
  const get = (name) => (text.match(new RegExp(`export const ${name} = "([^"]*)";`)) || [])[1];
  const hosts = [...((text.match(/export const PROD_HOSTS = \[([^\]]*)\];/) || [])[1] || "").matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  return { goatcounter: get("GOATCOUNTER"), form: get("PRO_FORM_URL"), contact: get("CONTACT_EMAIL"), controller: get("CONTROLLER"), site: get("SITE_URL"), hosts };
}

export function cspFor(goatcounter) {
  const gc = goatcounter ? ` https://${goatcounter}.goatcounter.com` : "";
  return `default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:${gc}; connect-src 'self'${gc}; object-src 'none'; base-uri 'none'; form-action 'none'`;
}

/** Response headers for hosts that read a _headers file (Cloudflare Pages); GitHub Pages ignores it. */
export function headersFile(goatcounter) {
  return ["# Generated by scripts/configure.mjs: do not edit by hand.", "/*",
    `  Content-Security-Policy: ${cspFor(goatcounter)}; frame-ancestors 'none'`,
    "  X-Content-Type-Options: nosniff", "  Referrer-Policy: no-referrer", "  X-Frame-Options: DENY",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=()", ""].join("\n");
}

// google*.html: Search Console verification files, not pages
export const pages = () => fs.readdirSync(WEB).filter((f) => f.endsWith(".html") && !/^google[0-9a-f]+\.html$/.test(f)).map((f) => path.join(WEB, f));
const CSP_RE = /<meta http-equiv="Content-Security-Policy" content="[^"]*">/;

function main(argv) {
  const args = Object.fromEntries(argv.reduce((acc, a, i) => (a.startsWith("--") ? [...acc, [a.slice(2), argv[i + 1]]] : acc), []));
  let text = fs.readFileSync(CONFIG, "utf8");
  const cfg = readConfig(text);
  if ("goatcounter" in args) {
    const v = args.goatcounter === "none" ? "" : String(args.goatcounter || "");
    if (v && !/^[a-z0-9][a-z0-9-]{1,48}$/.test(v)) throw new Error(`code GoatCounter invalide : ${v}`);
    cfg.goatcounter = v;
  }
  if ("form" in args) {
    const v = args.form === "none" ? "" : String(args.form || "");
    if (v && !/^https:\/\/tally\.so\/r\/[A-Za-z0-9]+$/.test(v)) throw new Error(`lien de formulaire invalide : ${v}`);
    cfg.form = v;
  }
  if ("contact" in args) {
    const v = args.contact === "none" ? "" : String(args.contact || "").trim();
    if (v && !/^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/.test(v)) throw new Error(`adresse de contact invalide : ${v}`);
    cfg.contact = v;
  }
  if ("controller" in args) {
    const v = args.controller === "none" ? "" : String(args.controller || "").trim();
    if (v && !/^[\p{L}][\p{L} .'-]{1,79}$/u.test(v)) throw new Error(`nom du responsable invalide : ${v}`);
    cfg.controller = v;
  }
  // statistics and the survey make the publisher a data controller: identity and contact must be published first
  // (GDPR art. 13(1)(a)); the founder chooses them, nothing is invented here
  // an e-mail contact also means receiving personal data: it needs the controller's name too
  if ((cfg.goatcounter || cfg.form || cfg.contact) && !(cfg.controller && cfg.contact)) {
    throw new Error("mesure d'audience ou questionnaire : renseignez d'abord --controller \"Nom\" et --contact adresse@dédiée");
  }
  let oldSite = cfg.site;
  if ("site" in args) {
    const v = String(args.site || "");
    if (!/^https:\/\/[a-z0-9.-]+\/([a-z0-9-]+\/)?$/.test(v)) throw new Error(`adresse invalide (https://hôte/ ou https://hôte/dossier/) : ${v}`);
    cfg.site = v;
    const host = new URL(v).host;
    if (!cfg.hosts.includes(host)) cfg.hosts.push(host); // the old host keeps counting while it redirects
  }
  const expected = cspFor(cfg.goatcounter);
  if ("check" in args) {
    const bad = pages().filter((p) => (fs.readFileSync(p, "utf8").match(CSP_RE) || [""])[0] !== `<meta http-equiv="Content-Security-Policy" content="${expected}">`);
    if (bad.length) { console.error(`CSP différente de la configuration : ${bad.map((p) => path.basename(p)).join(", ")}`); process.exit(1); }
    const hdr = path.join(WEB, "_headers");
    if (!fs.existsSync(hdr) || fs.readFileSync(hdr, "utf8").replace(/\r\n/g, "\n") !== headersFile(cfg.goatcounter)) { console.error("_headers différent de la configuration"); process.exit(1); }
    const privacy = fs.readFileSync(path.join(WEB, "privacy.html"), "utf8");
    if (renderPrivacy(privacy, cfg) !== privacy) { console.error("privacy.html ne décrit pas la configuration actuelle (relancez configure.mjs)"); process.exit(1); }
    console.log(`CSP cohérente sur ${pages().length} pages et dans _headers ; privacy.html conforme à la configuration`);
    return;
  }
  text = text.replace(/export const GOATCOUNTER = "[^"]*";/, `export const GOATCOUNTER = "${cfg.goatcounter}";`)
    .replace(/export const PRO_FORM_URL = "[^"]*";/, `export const PRO_FORM_URL = "${cfg.form}";`)
    .replace(/export const CONTACT_EMAIL = "[^"]*";/, `export const CONTACT_EMAIL = "${cfg.contact}";`)
    .replace(/export const CONTROLLER = "[^"]*";/, `export const CONTROLLER = "${cfg.controller}";`)
    .replace(/export const SITE_URL = "[^"]*";/, `export const SITE_URL = "${cfg.site}";`)
    .replace(/export const PROD_HOSTS = \[[^\]]*\];/, `export const PROD_HOSTS = [${cfg.hosts.map((h) => `"${h}"`).join(", ")}];`);
  fs.writeFileSync(CONFIG, text);
  fs.writeFileSync(path.join(WEB, "_headers"), headersFile(cfg.goatcounter));
  if (oldSite !== cfg.site) {
    // canonical URLs, sitemap and robots follow the new address; absolute links of 404.html follow its path
    const oldPath = new URL(oldSite).pathname, newPath = new URL(cfg.site).pathname;
    for (const f of [...pages(), path.join(WEB, "sitemap.xml"), path.join(WEB, "robots.txt")]) {
      let s = fs.readFileSync(f, "utf8").split(oldSite).join(cfg.site);
      if (f.endsWith("404.html") && oldPath !== "/") s = s.split(`"${oldPath}`).join(`"${newPath}`); // from a root address, 404 links stay as they are
      fs.writeFileSync(f, s);
    }
  }
  const privacyPath = path.join(WEB, "privacy.html");
  const before = fs.readFileSync(privacyPath, "utf8");
  let after = renderPrivacy(before, cfg);
  if (after !== before) { // the page changed: its "last updated" date follows
    const today = new Date().toLocaleDateString("fr-BE", { day: "numeric", month: "long", year: "numeric" });
    after = after.replace(/Dernière mise à jour : [^<]*<\/p>/, `Dernière mise à jour : ${today}.</p>`);
  }
  fs.writeFileSync(privacyPath, after);
  for (const p of pages()) {
    const html = fs.readFileSync(p, "utf8");
    if (!CSP_RE.test(html)) throw new Error(`${path.basename(p)} : balise CSP absente`);
    fs.writeFileSync(p, html.replace(CSP_RE, `<meta http-equiv="Content-Security-Policy" content="${expected}">`));
  }
  console.log(`adresse : ${cfg.site} · statistiques : ${cfg.goatcounter || "désactivées"} · questionnaire Pro : ${cfg.form || "masqué"} · contact : ${cfg.contact || "issues GitHub"} · CSP mise à jour sur ${pages().length} pages`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
